export const scenarioCopy = (locale: Locale, id: string): [string, string] => {
  const t = translations[locale];
  return id === "evidence-mixing"
    ? [t.evidenceMixing, t.mixDescription]
    : id === "scope-violation"
      ? [t.scopeViolation, t.scopeDescription]
      : [t.controlledSuccess, t.successDescription];
};

export function localizeTaskStatus(locale: Locale, status: string): string {
  const t = translations[locale];
  const values: Record<string, string> = {
    DRAFT: t.taskDraft,
    AWAITING_APPROVAL: t.taskAwaitingApproval,
    APPROVED: t.taskApproved,
    IN_EXECUTION: t.taskInExecution,
    AWAITING_DECISION: t.taskAwaitingDecision,
    CORRECTION_REQUESTED: t.taskCorrectionRequested,
    CLOSED: t.taskClosed,
    REJECTED: t.taskRejected,
  };
  return values[status] ?? status;
}

export function localizeRunSource(locale: Locale, source: RunSource): string {
  const t = translations[locale];
  if (source === "CORRECTION_REPORT") return t.correctedReport;
  return source === "IMPORTED_REPORT" ? t.importedReport : t.syntheticFixture;
}

